# recipes/imgui-w32/build.ps1 — compile Dear ImGui's core, with its 32-bit ImWchar, into
# imgui-w32.lib (MSVC) and install headers + backend sources under include\imgui-w32. The Windows
# analog of build.sh; ImGui ships no CMake install, so we compile the core translation units by
# hand with cl.exe.
#
# Static imgui-w32.lib on purpose: ImGui decorates no symbols with __declspec(dllexport),
# so a Windows DLL would export nothing and downstream links would fail. Consumers
# (e.g. cvcGL) link this static lib directly. The backends/ tree ships as SOURCE
# (headers + .cpp) — the consumer compiles the platform/renderer glue it needs.
#
# Unlike the imgui recipe's build.ps1 this writes the cmake package config too (find_package
# (imgui-w32), the imgui-w32::imgui target), as build.sh does, so a consumer finds it the same
# way on every platform.
$ErrorActionPreference = 'Stop'

if (-not $env:CVC_SOURCE_DIR) { throw 'CVC_SOURCE_DIR must be set' }
if (-not $env:CVC_INSTALL_DIR) { throw 'CVC_INSTALL_DIR must be set' }
if (-not $env:CVC_BUILD_DIR) { $env:CVC_BUILD_DIR = $env:CVC_SOURCE_DIR }

$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
. "$scriptDir\..\_common\env-windows.ps1" # imports MSVC (cl.exe/lib.exe), strips MinGW from PATH

Set-Location $env:CVC_SOURCE_DIR

$lib = Join-Path $env:CVC_INSTALL_DIR 'lib'
$incRoot = Join-Path $env:CVC_INSTALL_DIR 'include\imgui-w32'
$incBackends = Join-Path $incRoot 'backends'
$cmakeDir = Join-Path $lib 'cmake\imgui-w32'
New-Item -ItemType Directory -Force -Path $lib, $incRoot, $incBackends, $cmakeDir | Out-Null

# MSVC runtime: match the link mode (static -> /MT, shared -> /MD) so the CRT
# agrees with every other cvcpkg bundle in the prefix.
$crt = if ($env:CVC_LINK -eq 'static') { '/MT' } else { '/MD' }

# imconfig.h (patched) defines IMGUI_USE_WCHAR32, so the objects and every consumer agree.
$srcs = @('imgui.cpp', 'imgui_draw.cpp', 'imgui_tables.cpp', 'imgui_widgets.cpp', 'imgui_demo.cpp')
$objs = @()
foreach ($s in $srcs) {
    $obj = [System.IO.Path]::ChangeExtension($s, '.obj')
    & cl /nologo /std:c++17 /O2 /EHsc $crt /I. /c $s "/Fo$obj"
    if ($LASTEXITCODE -ne 0) { throw "cl failed on $s" }
    $objs += $obj
}

& lib /nologo "/OUT:$(Join-Path $lib 'imgui-w32.lib')" @objs
if ($LASTEXITCODE -ne 0) { throw 'lib.exe failed' }

# Public headers + the whole backends/ tree as source.
Copy-Item -Force imgui.h, imconfig.h, imgui_internal.h, `
    imstb_rectpack.h, imstb_textedit.h, imstb_truetype.h $incRoot
Copy-Item -Recurse -Force 'backends\*' $incBackends
# And the FreeType font loader, as source too: a consumer that links FreeType compiles it.
$incFreetype = Join-Path $incRoot 'misc\freetype'
New-Item -ItemType Directory -Force -Path $incFreetype | Out-Null
Copy-Item -Force 'misc\freetype\imgui_freetype.h', 'misc\freetype\imgui_freetype.cpp' $incFreetype

# The relocatable cmake package config, as write-cmake-config.sh writes it for the other
# platforms: the prefix comes from the config's own location when a consumer configures.
$config = @'
# Dear ImGui with a 32-bit ImWchar - cmake package config generated by the cvcpkg imgui-w32 recipe.
get_filename_component(_imgui_w32_prefix "${CMAKE_CURRENT_LIST_DIR}/../../.." REALPATH)
if(NOT TARGET imgui-w32::imgui)
  add_library(imgui-w32::imgui UNKNOWN IMPORTED)
  set_target_properties(imgui-w32::imgui PROPERTIES
    INTERFACE_INCLUDE_DIRECTORIES "${_imgui_w32_prefix}/include/imgui-w32"
    IMPORTED_LOCATION "${_imgui_w32_prefix}/lib/imgui-w32.lib")
endif()
unset(_imgui_w32_prefix)
'@
$version = @'
# Keep PACKAGE_VERSION in sync with the recipe's upstream_version.
set(PACKAGE_VERSION "1.92.9")
if(PACKAGE_VERSION VERSION_LESS PACKAGE_FIND_VERSION)
  set(PACKAGE_VERSION_COMPATIBLE FALSE)
else()
  set(PACKAGE_VERSION_COMPATIBLE TRUE)
  if(PACKAGE_VERSION VERSION_EQUAL PACKAGE_FIND_VERSION)
    set(PACKAGE_VERSION_EXACT TRUE)
  endif()
endif()
'@
[System.IO.File]::WriteAllText((Join-Path $cmakeDir 'imgui-w32Config.cmake'), $config.Replace("`r`n", "`n") + "`n")
[System.IO.File]::WriteAllText((Join-Path $cmakeDir 'imgui-w32ConfigVersion.cmake'), $version.Replace("`r`n", "`n") + "`n")

Invoke-CvcRewriteInstallPaths
