#!/usr/bin/env bash
# recipes/imgui-w32/write-cmake-config.sh PREFIX LIBRARY — write imgui-w32's cmake package
# config into PREFIX/lib/cmake/imgui-w32: find_package(imgui-w32) defines the imgui-w32::imgui
# imported target, PREFIX/lib/LIBRARY with PREFIX/include/imgui-w32 (whose imconfig.h defines
# IMGUI_USE_WCHAR32, so a consumer needs no flag of its own). The prefix is derived from
# the config's own location when a consumer configures, so it is relocatable.
#
# imgui's config defines imgui::imgui, so a project that finds both gets two targets, never one
# whose ABI depends on which was found first.
set -euo pipefail

prefix=$1 lib=$2
mkdir -p "${prefix}/lib/cmake/imgui-w32"
cat > "${prefix}/lib/cmake/imgui-w32/imgui-w32Config.cmake" <<CFG
# Dear ImGui with a 32-bit ImWchar - cmake package config generated by the cvcpkg imgui-w32 recipe.
get_filename_component(_imgui_w32_prefix "\${CMAKE_CURRENT_LIST_DIR}/../../.." REALPATH)
if(NOT TARGET imgui-w32::imgui)
  add_library(imgui-w32::imgui UNKNOWN IMPORTED)
  set_target_properties(imgui-w32::imgui PROPERTIES
    INTERFACE_INCLUDE_DIRECTORIES "\${_imgui_w32_prefix}/include/imgui-w32"
    IMPORTED_LOCATION "\${_imgui_w32_prefix}/lib/${lib}")
endif()
unset(_imgui_w32_prefix)
CFG
cat > "${prefix}/lib/cmake/imgui-w32/imgui-w32ConfigVersion.cmake" <<'VER'
# Keep PACKAGE_VERSION in sync with the recipe's upstream_version.
set(PACKAGE_VERSION "1.92.9")
if(PACKAGE_VERSION VERSION_LESS PACKAGE_FIND_VERSION)
  set(PACKAGE_VERSION_COMPATIBLE FALSE)
else()
  set(PACKAGE_VERSION_COMPATIBLE TRUE)
  if(PACKAGE_VERSION VERSION_EQUAL PACKAGE_FIND_VERSION)
    set(PACKAGE_VERSION_EXACT TRUE)
  endif()
endif()
VER
