#!/usr/bin/env bash
# recipes/wasmtime/build.sh — stage pre-built Wasmtime C API on Linux/macOS.
set -euo pipefail

WASMTIME_VER="45.0.0"

: "${CVC_INSTALL_DIR:?CVC_INSTALL_DIR must be set}"

# Determine the correct artifact name.
ARCH="$(uname -m)"
case "${CVC_PLATFORM}" in
    linux)
        [[ "${ARCH}" == "aarch64" ]] && ARCH="aarch64" || ARCH="x86_64"
        ARTIFACT="wasmtime-v${WASMTIME_VER}-${ARCH}-linux-c-api.tar.xz"
        ;;
    macos)
        [[ "${ARCH}" == "arm64" ]] && ARCH="aarch64" || ARCH="x86_64"
        ARTIFACT="wasmtime-v${WASMTIME_VER}-${ARCH}-macos-c-api.tar.xz"
        ;;
    *)
        echo "Unsupported platform: ${CVC_PLATFORM}" >&2
        exit 1
        ;;
esac

URL="https://github.com/bytecodealliance/wasmtime/releases/download/v${WASMTIME_VER}/${ARTIFACT}"
DOWNLOAD_DIR="${CVC_BUILD_DIR:-/tmp}"

echo "Downloading ${ARTIFACT}..."
curl -fSL -o "${DOWNLOAD_DIR}/${ARTIFACT}" "${URL}"

# Extract — the tarball contains a top-level directory.
mkdir -p "${DOWNLOAD_DIR}/wasmtime-extracted"
tar xf "${DOWNLOAD_DIR}/${ARTIFACT}" -C "${DOWNLOAD_DIR}/wasmtime-extracted" --strip-components=1

SRC="${DOWNLOAD_DIR}/wasmtime-extracted"

# Stage headers.
mkdir -p "${CVC_INSTALL_DIR}/include/wasmtime"
cp "${SRC}"/include/wasmtime.h "${CVC_INSTALL_DIR}/include/"
cp "${SRC}"/include/wasm.h    "${CVC_INSTALL_DIR}/include/"
cp "${SRC}"/include/wasi.h    "${CVC_INSTALL_DIR}/include/"
if [[ -d "${SRC}/include/wasmtime" ]]; then
    cp -r "${SRC}"/include/wasmtime/* "${CVC_INSTALL_DIR}/include/wasmtime/"
fi

# Stage libraries.
mkdir -p "${CVC_INSTALL_DIR}/lib"
cp "${SRC}"/lib/libwasmtime* "${CVC_INSTALL_DIR}/lib/" 2>/dev/null || true

# Name the Linux shared library. Upstream's libwasmtime.so has no DT_SONAME, so a
# consumer's linker records the path it was handed (CMake passes the full path, e.g.
# ../wt/lib/libwasmtime.so) as DT_NEEDED, and the consumer loads from nowhere else once
# installed. With a SONAME it records plain libwasmtime.so, found through its run path.
# The macOS dylib needs no such fix: it already names itself @rpath/libwasmtime.dylib.
if [[ "${CVC_PLATFORM}" == "linux" && -f "${CVC_INSTALL_DIR}/lib/libwasmtime.so" ]]; then
    # cvcpkg's patchelf (a build dependency), never one from the host.
    PATCHELF=""
    for _d in "${CVC_BUILD_PREFIX:-}" "${CVC_DEPS_PREFIX:-}"; do
        if [[ -n "${_d}" && -x "${_d}/bin/patchelf" ]]; then
            PATCHELF="${_d}/bin/patchelf"
            break
        fi
    done
    [[ -n "${PATCHELF}" ]] || {
        echo "wasmtime: cvcpkg's patchelf not found in CVC_BUILD_PREFIX or CVC_DEPS_PREFIX bin/" >&2
        exit 1
    }
    "${PATCHELF}" --set-soname libwasmtime.so "${CVC_INSTALL_DIR}/lib/libwasmtime.so"
    _soname="$("${PATCHELF}" --print-soname "${CVC_INSTALL_DIR}/lib/libwasmtime.so")"
    [[ "${_soname}" == "libwasmtime.so" ]] || {
        echo "wasmtime: libwasmtime.so has SONAME '${_soname}' after patchelf" >&2
        exit 1
    }
    echo "libwasmtime.so: SONAME ${_soname}"
fi

# Generate CMake config. wasmtime::wasmtime is the bundle's link variant: libwasmtime.a in a
# static bundle, the shared library in a shared one (or whichever of the two is present).
# CVC_LINK is unset only when this script runs outside cvcpkg; prefer the shared library then.
case "${CVC_LINK:-shared}" in
    static) WASMTIME_LINK=static ;;
    *) WASMTIME_LINK=shared ;;
esac
mkdir -p "${CVC_INSTALL_DIR}/lib/cmake/wasmtime"
{
    echo "# Generated by cvcpkg wasmtime recipe (${WASMTIME_LINK} bundle)."
    echo "set(_WASMTIME_LINK \"${WASMTIME_LINK}\")"
    cat <<'EOF'
get_filename_component(_WASMTIME_PREFIX "${CMAKE_CURRENT_LIST_DIR}/../../.." ABSOLUTE)

# A SHARED target names the library by its SONAME (install name on macOS), so a consumer
# records libwasmtime.so / @rpath/libwasmtime.dylib, never the path it was linked from.
if(APPLE)
    set(_WASMTIME_SHARED "${_WASMTIME_PREFIX}/lib/libwasmtime.dylib")
    set(_WASMTIME_SONAME "@rpath/libwasmtime.dylib")
else()
    set(_WASMTIME_SHARED "${_WASMTIME_PREFIX}/lib/libwasmtime.so")
    set(_WASMTIME_SONAME "libwasmtime.so")
endif()
set(_WASMTIME_STATIC "${_WASMTIME_PREFIX}/lib/libwasmtime.a")

set(wasmtime_FOUND TRUE)
if(NOT TARGET wasmtime::wasmtime)
    if(EXISTS "${_WASMTIME_STATIC}"
       AND (_WASMTIME_LINK STREQUAL "static" OR NOT EXISTS "${_WASMTIME_SHARED}"))
        add_library(wasmtime::wasmtime STATIC IMPORTED)
        set_target_properties(wasmtime::wasmtime PROPERTIES
            IMPORTED_LOCATION "${_WASMTIME_STATIC}"
            INTERFACE_INCLUDE_DIRECTORIES "${_WASMTIME_PREFIX}/include"
        )
        # What the archive needs from the system, as upstream's C API CMake lists it. On
        # macOS that is libSystem alone, which every link gets.
        if(UNIX AND NOT APPLE)
            set_property(TARGET wasmtime::wasmtime APPEND PROPERTY
                INTERFACE_LINK_LIBRARIES pthread dl m)
        endif()
    elseif(EXISTS "${_WASMTIME_SHARED}")
        add_library(wasmtime::wasmtime SHARED IMPORTED)
        set_target_properties(wasmtime::wasmtime PROPERTIES
            IMPORTED_LOCATION "${_WASMTIME_SHARED}"
            IMPORTED_SONAME "${_WASMTIME_SONAME}"
            INTERFACE_INCLUDE_DIRECTORIES "${_WASMTIME_PREFIX}/include"
        )
    else()
        set(wasmtime_FOUND FALSE)
        set(wasmtime_NOT_FOUND_MESSAGE
            "neither ${_WASMTIME_SHARED} nor ${_WASMTIME_STATIC} exists")
    endif()
endif()

unset(_WASMTIME_LINK)
unset(_WASMTIME_PREFIX)
unset(_WASMTIME_SHARED)
unset(_WASMTIME_SONAME)
unset(_WASMTIME_STATIC)
EOF
} > "${CVC_INSTALL_DIR}/lib/cmake/wasmtime/wasmtimeConfig.cmake"

cat > "${CVC_INSTALL_DIR}/lib/cmake/wasmtime/wasmtimeConfigVersion.cmake" <<EOF
set(PACKAGE_VERSION "${WASMTIME_VER}")
if("\${PACKAGE_FIND_VERSION}" VERSION_LESS_EQUAL PACKAGE_VERSION)
    set(PACKAGE_VERSION_COMPATIBLE TRUE)
    if("\${PACKAGE_FIND_VERSION}" VERSION_EQUAL PACKAGE_VERSION)
        set(PACKAGE_VERSION_EXACT TRUE)
    endif()
endif()
EOF

echo "Wasmtime ${WASMTIME_VER} C API staged to ${CVC_INSTALL_DIR}"

# ── Also fetch the CLI binary so that wasi tests can run ──
case "${CVC_PLATFORM}" in
    linux)
        CLI_ARTIFACT="wasmtime-v${WASMTIME_VER}-${ARCH}-linux.tar.xz"
        ;;
    macos)
        CLI_ARTIFACT="wasmtime-v${WASMTIME_VER}-${ARCH}-macos.tar.xz"
        ;;
esac

CLI_URL="https://github.com/bytecodealliance/wasmtime/releases/download/v${WASMTIME_VER}/${CLI_ARTIFACT}"
echo "Downloading ${CLI_ARTIFACT} (CLI)..."
curl -fSL -o "${DOWNLOAD_DIR}/${CLI_ARTIFACT}" "${CLI_URL}"

mkdir -p "${DOWNLOAD_DIR}/wasmtime-cli-extracted"
tar xf "${DOWNLOAD_DIR}/${CLI_ARTIFACT}" -C "${DOWNLOAD_DIR}/wasmtime-cli-extracted" --strip-components=1

mkdir -p "${CVC_INSTALL_DIR}/bin"
cp "${DOWNLOAD_DIR}/wasmtime-cli-extracted/wasmtime" "${CVC_INSTALL_DIR}/bin/wasmtime"
chmod +x "${CVC_INSTALL_DIR}/bin/wasmtime"
echo "Wasmtime CLI staged to ${CVC_INSTALL_DIR}/bin/wasmtime"
