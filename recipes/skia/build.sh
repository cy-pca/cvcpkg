#!/usr/bin/env bash
# recipes/skia/build.sh — clone + GN build Skia on Linux/macOS.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
source "${SCRIPT_DIR}/../_common/env-${CVC_PLATFORM}.sh"

SKIA_TAG="chrome/m137"

# Network steps get three tries.  git-sync-deps clones ~30 third-party repos
# from googlesource, and one "fatal: remote transport reported error" failed the
# whole build on the 2026-10-14 linux fleet populate.  Both steps are safe to
# re-run: the clone is retried into a fresh directory, and git-sync-deps
# resumes.
_retry() {  # what, command...
    local what="$1" _try
    shift
    for _try in 1 2 3; do
        "$@" && return 0
        [ "${_try}" = 3 ] && break
        echo "skia: ${what} failed (attempt ${_try}/3); retrying in $((_try * 30))s" >&2
        sleep $((_try * 30))
    done
    echo "skia: ${what} failed 3 times" >&2
    return 1
}

# --- 1. Clone (or update) skia. ---
SRC="${CVC_SOURCE_DIR}/skia"
_clone_skia() {
    rm -rf "${SRC}"
    git clone --depth=1 --branch "${SKIA_TAG}" https://skia.googlesource.com/skia.git "${SRC}"
}
if [[ ! -d "${SRC}/.git" ]]; then
    _retry "cloning skia" _clone_skia
fi
cd "${SRC}"

# --- 2. Sync DEPS. ---
# Through sync_deps.py: one repository at a time with its own retries, naming any
# that keeps failing (upstream's runs ~40 clones at once and reports only "Thread
# failure detected"; five failed on every attempt on the 2026-10-15 fleet run).
_retry "git-sync-deps" python3 "${SCRIPT_DIR}/sync_deps.py" tools/git-sync-deps

# --- 3. GN args. ---
if [[ "${CVC_LINK:-shared}" == "static" ]]; then
    IS_COMPONENT="false"
else
    IS_COMPONENT="true"
fi

case "${CVC_PLATFORM}" in
    linux)
        GN_TARGET_OS='"linux"'
        ;;
    macos)
        GN_TARGET_OS='"mac"'
        ;;
esac

# Linux builds the GLX GL backend: GL/gl.h and GL/glx.h come from cvcpkg's
# libglvnd and Xlib from libx11 (recipe.yaml), not the build host, which on the
# linux/arm64 runners has none ("GL/gl.h: No such file or directory").
GN_CFLAGS='"-fPIC"'
GN_LDFLAGS=''
if [[ "${CVC_PLATFORM}" == "linux" ]]; then
    GN_CFLAGS="${GN_CFLAGS},\"-I${CVC_DEPS_PREFIX}/include\""
    GN_LDFLAGS="\"-L${CVC_DEPS_PREFIX}/lib\""
fi

GN_ARGS="is_official_build=true is_component_build=${IS_COMPONENT} \
skia_use_system_expat=false skia_use_system_freetype2=false \
skia_use_system_harfbuzz=false skia_use_system_icu=false \
skia_use_system_libjpeg_turbo=false skia_use_system_libpng=false \
skia_use_system_libwebp=false skia_use_system_zlib=false \
skia_enable_tools=false skia_enable_gpu=true \
target_os=${GN_TARGET_OS} extra_cflags=[${GN_CFLAGS}] extra_ldflags=[${GN_LDFLAGS}]"

OUT="${CVC_BUILD_DIR}/out"
bin/gn gen "${OUT}" --args="${GN_ARGS}"
ninja -C "${OUT}" -j "${CVC_JOBS}" skia skshaper skparagraph skunicode

# --- 4. Stage headers + libs. ---
mkdir -p "${CVC_INSTALL_DIR}/include/skia" \
         "${CVC_INSTALL_DIR}/lib" \
         "${CVC_INSTALL_DIR}/share/skia"

for pat in libskia.* libskshaper.* libskparagraph.* libskunicode.*; do
    cp "${OUT}"/${pat} "${CVC_INSTALL_DIR}/lib/" 2>/dev/null || true
done

# Copy public headers (include/), modules headers, and gn/ tool metadata.
cp -R include/* "${CVC_INSTALL_DIR}/include/skia/"
for m in modules/skshaper/include modules/skparagraph/include modules/skunicode/include; do
    if [[ -d "$m" ]]; then
        cp -R "$m"/* "${CVC_INSTALL_DIR}/include/skia/"
    fi
done

# --- 5. Minimal CMake package config. ---
mkdir -p "${CVC_INSTALL_DIR}/lib/cmake/Skia"
cat > "${CVC_INSTALL_DIR}/lib/cmake/Skia/SkiaConfig.cmake" << 'CMAKE'
# SkiaConfig.cmake — generated by cvcpkg (libcvc-deps)
get_filename_component(_skia_root "${CMAKE_CURRENT_LIST_DIR}/../../.." ABSOLUTE)

foreach(_lib skia skshaper skparagraph skunicode)
    if(NOT TARGET Skia::${_lib})
        add_library(Skia::${_lib} UNKNOWN IMPORTED)
        find_library(_skia_${_lib}_path NAMES ${_lib} HINTS "${_skia_root}/lib" NO_DEFAULT_PATH)
        set_target_properties(Skia::${_lib} PROPERTIES
            IMPORTED_LOCATION             "${_skia_${_lib}_path}"
            INTERFACE_INCLUDE_DIRECTORIES "${_skia_root}/include/skia"
            INTERFACE_COMPILE_FEATURES    "cxx_std_17")
    endif()
endforeach()
CMAKE

echo "skia (chrome/m137) installed to ${CVC_INSTALL_DIR}"
