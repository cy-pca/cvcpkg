#!/usr/bin/env python3
"""Split a tarball recipe into a source package and a recipe that builds from it.

usage: tools/make_source_package.py [--recipes-dir recipes] NAME...

For each recipe NAME whose source is a single pinned tarball, this writes the
source recipe ``NAME-src`` (docs/source-recipes.md): ``platform: any``, the
same upstream tarball and sha256, and a build.sh that stages the extracted tree
at ``src/NAME-src/``.  NAME's own ``source:`` block becomes
``{type: package, package: NAME-src}`` and NAME-src is added to its
``depends.build``.

The tarball is then downloaded once, by whichever builder publishes the noarch
NAME-src bundle, and every other build of NAME -- another platform or arch, a
builder that cannot reach the upstream host, an end user building from source
-- installs that bundle from the catalog instead.  NAME's bundle content does
not change (same tarball, same patches), so its cvc_revision is left alone.

Edits are textual so each recipe keeps its comments and layout; anything the
tool cannot edit with confidence is reported and left untouched.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

BUILD_SH = """\
#!/usr/bin/env bash
# recipes/{src}/build.sh -- stage {name}'s upstream source tree at src/{src}/
# (a source package: see docs/source-recipes.md).  Generated by
# tools/make_source_package.py.
set -euo pipefail
# shellcheck disable=SC1091
. "$(dirname "$0")/../_common/stage-source.sh"
cvc_stage_source
"""

RECIPE_YAML = """\
schema_version: 1
recipe:
  name: {src}
  upstream_version: "{version}"
  cvc_revision: 1
  maintainer: {maintainer}
  maintainer_email: {maintainer_email}
  maintainer_url: {maintainer_url}
  homepage: {homepage}
  license: {license}
  tags: [source]
  description: >-
    The unmodified upstream source of {name} {version}: its release tarball,
    verified against the sha256 below and staged at src/{src}/.  The {name}
    recipe builds from it (source.type package), so the tarball is fetched
    once, from {host}, and every other build of {name} -- another
    platform, a builder that cannot reach {host}, a user building from
    source -- installs this package from the catalog instead.  Generated by
    tools/make_source_package.py.

{source}
patches: []

depends:
  build: []
  runtime: []
  host_tools: []

build:
  build_type_independent: true
  matrix:
    - platform: any
      script: build.sh

package:
  files:
    - src/{src}/
"""


def q(value: object) -> str:
    """A YAML scalar for *value* (quoted the way yaml.dump would, if needed)."""
    return (
        yaml.safe_dump(value, default_flow_style=True, width=1000)
        .strip()
        .removesuffix("...")
        .strip()
    )


def top_level_block(text: str, key: str) -> tuple[int, int] | None:
    """(start, end) offsets of the top-level ``key:`` block, through its last line."""
    m = re.search(rf"^{key}:.*\n", text, re.M)
    if not m:
        return None
    nxt = re.search(r"^[A-Za-z_][\w-]*:", text[m.end() :], re.M)
    end = m.end() + nxt.start() if nxt else len(text)
    # Blank lines and column-0 comments just before the next key belong to it.
    lines = text[m.start() : end].splitlines(keepends=True)
    while len(lines) > 1 and (not lines[-1].strip() or lines[-1].startswith("#")):
        lines.pop()
    return m.start(), m.start() + sum(len(x) for x in lines)


def pinnable(version: str) -> str:
    """*version* if cvcpkg can pin it exactly (``==``), else "" (left unpinned)."""
    try:
        from cvcpkg.semver import Version

        Version.parse(version)
    except Exception:
        return ""
    return version


def add_build_dep(text: str, dep: str, version: str = "") -> str | None:
    """*text* with *dep* (pinned to *version*, if given) added to depends.build.

    None if the layout is unexpected.
    """
    if version:
        item = f'    - name: {dep}\n      version: "=={version}"\n'
    else:
        item = f"    - {dep}\n"
    block = top_level_block(text, "depends")
    if block is None:
        b = top_level_block(text, "build")
        if b is None:
            return None
        ins = "depends:\n  build:\n" + item + "  runtime: []\n  host_tools: []\n\n"
        return text[: b[0]] + ins + text[b[0] :]
    start, end = block
    body = text[start:end]
    m = re.search(r"^  build:[ \t]*\[\][ \t]*\n", body, re.M)
    if m:
        body = body[: m.start()] + "  build:\n" + item + body[m.end() :]
        return text[:start] + body + text[end:]
    m = re.search(r"^  build:[ \t]*\n", body, re.M)
    if m:
        body = body[: m.end()] + item + body[m.end() :]
        return text[:start] + body + text[end:]
    m = re.search(r"^depends:[ \t]*\n", body, re.M)
    if m and not re.search(r"^  build:", body, re.M):
        body = body[: m.end()] + "  build:\n" + item + body[m.end() :]
        return text[:start] + body + text[end:]
    return None


def convert(recipes_dir: Path, name: str) -> str:
    rdir = recipes_dir / name
    path = rdir / "recipe.yaml"
    text = path.read_text(encoding="utf-8")
    doc = yaml.safe_load(text)
    src_name = f"{name}-src"
    source = doc.get("source") or {}
    if source.get("type") != "tarball":
        return f"skip {name}: source.type is {source.get('type')!r}, not tarball"
    if source.get("artifacts"):
        return f"skip {name}: per-platform artifacts (a prebuilt download, not one source)"
    if not source.get("sha256"):
        return f"skip {name}: no sha256 pin"
    if (recipes_dir / src_name).exists():
        return f"skip {name}: {src_name} already exists"
    block = top_level_block(text, "source")
    if block is None:
        return f"skip {name}: no top-level source: block found"
    start, end = block
    source_text = text[start:end]

    new_text = (
        text[:start]
        + "source:\n"
        + f"  # Built from the source package {src_name}, which pins the upstream tarball\n"
        + f"  # ({source['url']}).\n"
        + "  type: package\n"
        + f"  package: {src_name}\n"
        + text[end:]
    )
    new_text = add_build_dep(new_text, src_name, pinnable(str(doc["recipe"]["upstream_version"])))
    if new_text is None:
        return f"skip {name}: could not add {src_name} to depends.build (unexpected layout)"

    rec = doc.get("recipe") or {}
    host = re.sub(r"^\w+://([^/]+)/.*$", r"\1", source["url"])
    srcdir = recipes_dir / src_name
    srcdir.mkdir()
    (srcdir / "recipe.yaml").write_text(
        RECIPE_YAML.format(
            src=src_name,
            name=name,
            version=rec["upstream_version"],
            maintainer=q(rec.get("maintainer", "cvcpkg group")),
            maintainer_email=q(rec.get("maintainer_email", "info@cvcpkg.org")),
            maintainer_url=q(rec.get("maintainer_url", "https://cvcpkg.org")),
            homepage=q(rec.get("homepage", source["url"])),
            license=q(rec.get("license", "NOASSERTION")),
            host=host,
            source=source_text,
        ),
        encoding="utf-8",
        newline="\n",
    )
    build = srcdir / "build.sh"
    build.write_text(BUILD_SH.format(src=src_name, name=name), encoding="utf-8", newline="\n")
    build.chmod(0o755)
    path.write_text(new_text, encoding="utf-8", newline="\n")
    return f"ok   {name} -> {src_name}"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--recipes-dir", default="recipes", type=Path)
    ap.add_argument("names", nargs="+")
    args = ap.parse_args(argv)
    bad = 0
    for name in args.names:
        msg = convert(args.recipes_dir, name)
        print(msg)
        bad += not msg.startswith("ok")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
