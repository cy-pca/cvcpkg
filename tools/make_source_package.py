#!/usr/bin/env python3
"""Split a tarball recipe into a source package and a recipe that builds from it.

usage: tools/make_source_package.py [--recipes-dir recipes] [--src SRC] NAME...

For each recipe NAME whose source is a single pinned tarball, this writes the
source recipe ``NAME-src`` (docs/source-recipes.md): ``platform: any``, the
same upstream tarball and sha256, and a build.sh that stages the extracted tree
at ``src/NAME-src/``.  NAME's own ``source:`` block becomes
``{type: package, package: NAME-src}`` and NAME-src is added to its
``depends.build``.

Recipes that build the same tarball share one source package.  The NAMEs
given are grouped by their source block, and each group's package is named
after what its members have in common: the ``-cp3XX[t]`` interpreter suffix
dropped (``pyyaml-cp311`` ... ``pyyaml-cp313t`` -> ``pyyaml-src``), then the
shortest name if every other one extends it (``ffmpeg``, ``ffmpeg-cli`` ->
``ffmpeg-src``; ``vtk``, ``vtk-python-cp312`` -> ``vtk-src``).  ``--src``
names it instead, for one group whose names have nothing in common
(``pyside6-cp3XX`` and ``shiboken6-cp3XX`` build pyside-setup).  A source
recipe that already exists for the same tarball is reused, so a recipe added
later joins its siblings' package.  Two groups that would get one name (an
older pin of ``numpy-cp311`` beside ``numpy-cp312``...) are not merged: the
larger keeps the name and a lone recipe falls back to ``NAME-src``.

The tarball is then downloaded once, by whichever builder publishes the noarch
NAME-src bundle, and every other build of NAME -- another platform or arch, a
builder that cannot reach the upstream host, an end user building from source
-- installs that bundle from the catalog instead.  NAME's bundle content does
not change (same tarball, same patches), so its cvc_revision is left alone.

Edits are textual so each recipe keeps its comments and layout; anything the
tool cannot edit with confidence is reported and left untouched.
"""

from __future__ import annotations

import argparse
import re
import sys
import textwrap
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

BUILD_SH = """\
#!/usr/bin/env bash
# recipes/{src}/build.sh -- stage {name}'s upstream source tree at src/{src}/
# (a source package: see docs/source-recipes.md).  Generated by
# tools/make_source_package.py.
set -euo pipefail
# shellcheck disable=SC1091
. "$(dirname "$0")/../_common/stage-source.sh"
cvc_stage_source
"""

DESCRIPTION = (
    "The unmodified upstream source of {project} {version}: its release tarball, "
    "verified against the sha256 below and staged at src/{src}/.  {users} from it "
    "(source.type package), so the tarball is fetched once, from {host}, and every "
    "other build of {them} -- another platform, a builder that cannot reach {host}, "
    "a user building from source -- installs this package from the catalog instead.  "
    "Generated by tools/make_source_package.py."
)

RECIPE_YAML = """\
schema_version: 1
recipe:
  name: {src}
  upstream_version: "{version}"
  cvc_revision: 1
  maintainer: {maintainer}
  maintainer_email: {maintainer_email}
  maintainer_url: {maintainer_url}
  homepage: {homepage}
  license: {license}
  tags: [source]
  description: >-
{description}

{source}
patches: []

depends:
  build: []
  runtime: []
  host_tools: []

build:
  build_type_independent: true
  matrix:
    - platform: any
      script: build.sh

package:
  files:
    - src/{src}/
"""


def q(value: object) -> str:
    """A YAML scalar for *value* (quoted the way yaml.dump would, if needed)."""
    return (
        yaml.safe_dump(value, default_flow_style=True, width=1000)
        .strip()
        .removesuffix("...")
        .strip()
    )


def top_level_block(text: str, key: str) -> tuple[int, int] | None:
    """(start, end) offsets of the top-level ``key:`` block, through its last line."""
    m = re.search(rf"^{key}:.*\n", text, re.M)
    if not m:
        return None
    nxt = re.search(r"^[A-Za-z_][\w-]*:", text[m.end() :], re.M)
    end = m.end() + nxt.start() if nxt else len(text)
    # Blank lines and column-0 comments just before the next key belong to it.
    lines = text[m.start() : end].splitlines(keepends=True)
    while len(lines) > 1 and (not lines[-1].strip() or lines[-1].startswith("#")):
        lines.pop()
    return m.start(), m.start() + sum(len(x) for x in lines)


def pinnable(version: str) -> str:
    """*version* if cvcpkg can pin it exactly (``==``), else "" (left unpinned)."""
    try:
        from cvcpkg.semver import Version

        Version.parse(version)
    except Exception:
        return ""
    return version


def add_build_dep(text: str, dep: str, version: str = "") -> str | None:
    """*text* with *dep* (pinned to *version*, if given) added to depends.build.

    None if the layout is unexpected.
    """
    if version:
        item = f'    - name: {dep}\n      version: "=={version}"\n'
    else:
        item = f"    - {dep}\n"
    block = top_level_block(text, "depends")
    if block is None:
        b = top_level_block(text, "build")
        if b is None:
            return None
        ins = "depends:\n  build:\n" + item + "  runtime: []\n  host_tools: []\n\n"
        return text[: b[0]] + ins + text[b[0] :]
    start, end = block
    body = text[start:end]
    m = re.search(r"^  build:[ \t]*\[\][ \t]*\n", body, re.M)
    if m:
        body = body[: m.start()] + "  build:\n" + item + body[m.end() :]
        return text[:start] + body + text[end:]
    m = re.search(r"^  build:[ \t]*\n", body, re.M)
    if m:
        body = body[: m.end()] + item + body[m.end() :]
        return text[:start] + body + text[end:]
    m = re.search(r"^depends:[ \t]*\n", body, re.M)
    if m and not re.search(r"^  build:", body, re.M):
        body = body[: m.end()] + "  build:\n" + item + body[m.end() :]
        return text[:start] + body + text[end:]
    return None


_PY_ABI = re.compile(r"-cp3\d+t?$")


def shared_name(names: list[str]) -> str | None:
    """The source package for recipes that build one tarball, if a name is evident.

    The interpreter suffix is dropped first, then the shortest base is used if
    every other base extends it; None if the names have nothing in common.
    """
    bases = sorted({_PY_ABI.sub("", n) for n in names}, key=lambda b: (len(b), b))
    if all(b == bases[0] or b.startswith(bases[0] + "-") for b in bases):
        return f"{bases[0]}-src"
    return None


def joined(items: list[str]) -> str:
    """'a', 'a and b', 'a, b and c'."""
    return items[0] if len(items) == 1 else ", ".join(items[:-1]) + " and " + items[-1]


def licenses(recs: list[dict]) -> str:
    """The licenses of *recs* (one tarball): the shared one, or all of them ANDed."""
    seen: list[str] = []
    for rec in recs:
        lic = str(rec.get("license", "NOASSERTION"))
        if lic not in seen:
            seen.append(lic)
    if len(seen) == 1:
        return seen[0]
    return " AND ".join(f"({x})" if " OR " in x else x for x in seen)


class Member:
    """One recipe to rebuild from a source package."""

    def __init__(self, recipes_dir: Path, name: str):
        self.name = name
        self.path = recipes_dir / name / "recipe.yaml"
        self.text = self.path.read_text(encoding="utf-8")
        self.doc = yaml.safe_load(self.text)
        self.source = self.doc.get("source") or {}
        self.rec = self.doc.get("recipe") or {}

    def refusal(self) -> str | None:
        """Why this recipe cannot be split, or None."""
        if self.source.get("type") != "tarball":
            return f"source.type is {self.source.get('type')!r}, not tarball"
        if self.source.get("artifacts"):
            return "per-platform artifacts (a prebuilt download, not one source)"
        if not self.source.get("sha256"):
            return "no sha256 pin"
        if top_level_block(self.text, "source") is None:
            return "no top-level source: block found"
        return None

    def key(self) -> str:
        """The source block, normalized: recipes with equal keys build one tree."""
        return source_key(self.source)


def source_key(source: dict) -> str:
    return yaml.safe_dump(source, sort_keys=True)


def existing_recipe(recipes_dir: Path, src_name: str) -> dict | None:
    """The parsed recipe *src_name*; None if there is no such recipe."""
    path = recipes_dir / src_name / "recipe.yaml"
    if not path.is_file():
        return None
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def write_source_recipe(recipes_dir: Path, src_name: str, members: list[Member]) -> None:
    first = members[0]
    rec = first.rec
    names = [m.name for m in members]
    url = first.source["url"]
    host = re.sub(r"^\w+://([^/]+)/.*$", r"\1", url)
    start, end = top_level_block(first.text, "source")
    srcdir = recipes_dir / src_name
    srcdir.mkdir()
    (srcdir / "recipe.yaml").write_text(
        RECIPE_YAML.format(
            src=src_name,
            description=textwrap.fill(
                DESCRIPTION.format(
                    project=src_name.removesuffix("-src"),
                    version=rec["upstream_version"],
                    src=src_name,
                    users=(
                        f"The {names[0]} recipe builds"
                        if len(names) == 1
                        else f"The {joined(names)} recipes build"
                    ),
                    host=host,
                    them=names[0] if len(names) == 1 else "them",
                ),
                width=80,
                initial_indent="    ",
                subsequent_indent="    ",
                break_on_hyphens=False,
                break_long_words=False,
            ),
            version=rec["upstream_version"],
            maintainer=q(rec.get("maintainer", "cvcpkg group")),
            maintainer_email=q(rec.get("maintainer_email", "info@cvcpkg.org")),
            maintainer_url=q(rec.get("maintainer_url", "https://cvcpkg.org")),
            homepage=q(rec.get("homepage", url)),
            license=q(licenses([m.rec for m in members])),
            source=first.text[start:end],
        ),
        encoding="utf-8",
        newline="\n",
    )
    build = srcdir / "build.sh"
    build.write_text(
        BUILD_SH.format(src=src_name, name=joined(names)), encoding="utf-8", newline="\n"
    )
    build.chmod(0o755)


def rewrite(member: Member, src_name: str, version: str) -> str | None:
    """*member*'s recipe text, built from *src_name*; None if the layout is unexpected."""
    text = member.text
    start, end = top_level_block(text, "source")
    new_text = (
        text[:start]
        + "source:\n"
        + f"  # Built from the source package {src_name}, which pins the upstream tarball\n"
        + f"  # ({member.source['url']}).\n"
        + "  type: package\n"
        + f"  package: {src_name}\n"
        + text[end:]
    )
    return add_build_dep(new_text, src_name, pinnable(version))


def assign(
    recipes_dir: Path, groups: list[list[Member]], src: str | None
) -> list[tuple[str | None, list[Member], str]]:
    """(source package or None, members, note) for each group building one tarball.

    A source recipe already staging the same tarball comes first, whatever its
    name.  Larger groups choose first, so of two pins of one project, the one
    more recipes build gets the project's name.
    """
    staged: dict[str, str] = {}
    for path in sorted(recipes_dir.glob("*-src/recipe.yaml")):
        have = existing_recipe(recipes_dir, path.parent.name) or {}
        staged.setdefault(source_key(have.get("source") or {}), path.parent.name)
    claimed: dict[str, str] = {}
    out = []
    for group in sorted(groups, key=lambda g: -len(g)):
        names = [m.name for m in group]
        key = group[0].key()
        candidates = [src] if src else [staged.get(key) or shared_name(names)]
        if not src and len(group) == 1 and candidates[0] != f"{names[0]}-src":
            candidates.append(f"{names[0]}-src")
        chosen, note = None, ""
        for cand in candidates:
            if cand is None:
                note = "these build one tarball but share no name; pass --src NAME"
                continue
            if claimed.get(cand, key) != key:
                note = f"{cand} is taken by another tarball in this run"
                continue
            have = existing_recipe(recipes_dir, cand)
            if have is not None:
                if source_key(have.get("source") or {}) != key:
                    note = f"{cand} already exists for another tarball"
                    continue
                note = f"reusing {cand}"
            chosen = cand
            break
        if chosen:
            claimed[chosen] = key
        out.append((chosen, group, note))
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--recipes-dir", default="recipes", type=Path)
    ap.add_argument(
        "--src", help="the source package's name (every NAME must build the same tarball)"
    )
    ap.add_argument("names", nargs="+")
    args = ap.parse_args(argv)
    bad = 0
    groups: dict[str, list[Member]] = {}
    for name in args.names:
        if not (args.recipes_dir / name / "recipe.yaml").is_file():
            print(f"skip {name}: no such recipe")
            bad += 1
            continue
        member = Member(args.recipes_dir, name)
        why = member.refusal()
        if why:
            print(f"skip {name}: {why}")
            bad += 1
            continue
        groups.setdefault(member.key(), []).append(member)
    if args.src and len(groups) > 1:
        print(
            f"skip all: --src {args.src} names one source package, but these build "
            f"{len(groups)} different tarballs"
        )
        return 1
    for src_name, members, note in assign(args.recipes_dir, list(groups.values()), args.src):
        names = ", ".join(m.name for m in members)
        if src_name is None:
            print(f"skip {names}: {note}")
            bad += len(members)
            continue
        existing = existing_recipe(args.recipes_dir, src_name)
        version = str((existing or members[0].doc)["recipe"]["upstream_version"])
        texts = [rewrite(m, src_name, version) for m in members]
        odd = [m.name for m, text in zip(members, texts, strict=True) if text is None]
        if odd:
            print(
                f"skip {names}: could not add {src_name} to depends.build of "
                f"{', '.join(odd)} (unexpected layout)"
            )
            bad += len(members)
            continue
        if existing is None:
            write_source_recipe(args.recipes_dir, src_name, members)
        for m, text in zip(members, texts, strict=True):
            m.path.write_text(text, encoding="utf-8", newline="\n")
        print(f"ok   {names} -> {src_name}{f' ({note})' if note else ''}")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
