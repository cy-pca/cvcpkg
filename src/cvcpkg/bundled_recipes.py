"""The standard recipes embedded in the frozen single-file binary.

A PyInstaller onefile binary unpacks every bundled *data* file into a fresh
temp directory on every start.  The recipe tree is ~3,300 small files, so
shipping it as data made each start pay for writing (and, on Windows, for
Defender scanning) all of them -- 5-13 s for ``cvcpkg --version`` on Windows.

Instead ``packaging/cvcpkg.spec`` embeds the tree as ONE zip in a generated
module, :data:`MODULE`, which PyInstaller compiles into the PYZ archive.  The
bootloader reads the PYZ in place from the executable and never unpacks it, so
a start that does not touch recipes writes no recipe files at all.

Recipe consumers want a directory (``Recipe.load``, chain hashes, and the
build scripts bash/pwsh run from it), so :func:`embedded_recipes_dir` writes
the tree once per recipe digest into the user cache and every later start
reuses it.  The embedded set is only the *default* recipes directory:
``--recipes-dir`` and the ``./recipes`` overlay still layer after it and win
on name conflicts, exactly as they did over the unpacked bundle.
"""

from __future__ import annotations

import hashlib
import io
import os
import shutil
import stat
import sys
import tempfile
import time
import zipfile
from pathlib import Path

# The generated module (see write_module).  Top-level, so generating it never
# shadows or collides with the cvcpkg package being frozen.
MODULE = "cvcpkg_embedded_recipes"

# Written into ``<digest>/`` after its tree is complete; a tree without it is
# never used.
_COMPLETE = ".complete"

# Unpacked trees kept per cache, newest first.  More than one, so a builder
# still running the previous binary during a self-update keeps its tree.
_KEEP = 3

# Abandoned ``.tmp-*`` unpack dirs older than this are removed.
_STALE_TMP_SECONDS = 24 * 3600

# Zip entry timestamps are pinned so identical trees give identical archives.
_ZIP_EPOCH = (1980, 1, 1, 0, 0, 0)


def build_archive(src: Path) -> bytes:
    """Zip the recipe tree *src* as ``recipes/...``, reproducibly.

    Entries are sorted and their timestamps pinned; each keeps its POSIX mode,
    which :func:`_unpack` restores.
    """
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as zf:
        for path in sorted(p for p in src.rglob("*") if p.is_file()):
            rel = path.relative_to(src).as_posix()
            info = zipfile.ZipInfo(f"recipes/{rel}", date_time=_ZIP_EPOCH)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = (stat.S_IFREG | (path.stat().st_mode & 0o777)) << 16
            zf.writestr(info, path.read_bytes())
    return buf.getvalue()


def write_module(src: Path, dest_dir: Path) -> Path:
    """Generate ``<dest_dir>/<MODULE>.py`` embedding the recipe tree *src*.

    The module defines ``DIGEST`` (sha256 of the archive) and ``DATA`` (the
    archive).  Called by ``packaging/cvcpkg.spec`` at freeze time.
    """
    data = build_archive(src)
    dest_dir.mkdir(parents=True, exist_ok=True)
    out = dest_dir / f"{MODULE}.py"
    out.write_text(
        "# Generated by packaging/cvcpkg.spec from recipes/ -- do not edit.\n"
        f"DIGEST = {hashlib.sha256(data).hexdigest()!r}\n"
        f"DATA = {data!r}\n",
        encoding="ascii",
    )
    return out


def _embedded():
    """The generated module, or None outside a binary that embeds recipes."""
    try:
        return __import__(MODULE)
    except ImportError:
        return None


def _cache_root() -> Path:
    from cvcpkg.cache import BUNDLED_RECIPES_SUBDIR, default_cache_dir

    # One ``<digest>/recipes`` tree per embedded set; `cvcpkg gc` skips it.
    return default_cache_dir() / BUNDLED_RECIPES_SUBDIR


def embedded_recipes_dir(cache_root: Path | None = None) -> Path | None:
    """The embedded recipes as a directory, or None if none are embedded.

    Unpacks them on first use into ``<cache_root>/<digest>/recipes`` (default
    cache root: ``<cvcpkg cache>/bundled-recipes``).  When the cache cannot be
    written, unpacks into ``sys._MEIPASS`` instead, which the bootloader
    removes at exit: correct, just not reused by the next start.
    """
    mod = _embedded()
    if mod is None:
        return None
    root = cache_root if cache_root is not None else _cache_root()
    target = root / mod.DIGEST[:16]
    if (target / _COMPLETE).is_file():
        return target / "recipes"
    try:
        tree = _unpack_into_cache(mod.DATA, root, target)
    except OSError:
        meipass = getattr(sys, "_MEIPASS", None)
        if not meipass:
            raise
        tree = Path(meipass) / "cvcpkg-embedded-recipes"
        if not (tree / _COMPLETE).is_file():
            _unpack(mod.DATA, tree)
    _prune(root, keep=tree)
    return tree / "recipes"


def _unpack(data: bytes, dest: Path) -> None:
    """Write the archive *data* under *dest*, then mark *dest* complete."""
    with zipfile.ZipFile(io.BytesIO(data)) as zf:
        zf.extractall(dest)
        if os.name != "nt":
            for info in zf.infolist():
                mode = (info.external_attr >> 16) & 0o777
                if mode:
                    os.chmod(dest / info.filename, mode)
    (dest / _COMPLETE).write_text("")


def _unpack_into_cache(data: bytes, root: Path, target: Path) -> Path:
    """Unpack into a private temp dir under *root* and rename it to *target*.

    The rename is the commit point, so concurrent starts (a fleet launching
    its workers) never see a half-written tree: each unpacks its own copy and
    the first rename wins.  Returns the directory to use, which is the temp
    dir itself when Windows keeps refusing the rename (an antivirus scanner
    holding a just-written file open); that copy is complete, and a later
    start retries the rename.
    """
    root.mkdir(parents=True, exist_ok=True)
    tmp = Path(tempfile.mkdtemp(prefix=f".tmp-{target.name}-", dir=root))
    try:
        _unpack(data, tmp)
    except BaseException:
        shutil.rmtree(tmp, ignore_errors=True)
        raise
    for attempt in range(5):
        if (target / _COMPLETE).is_file():  # another process won the race
            shutil.rmtree(tmp, ignore_errors=True)
            return target
        if target.exists():  # left incomplete by something other than us
            shutil.rmtree(target, ignore_errors=True)
        try:
            tmp.rename(target)
            return target
        except OSError:
            time.sleep(0.2 * (attempt + 1))
    if (target / _COMPLETE).is_file():
        shutil.rmtree(tmp, ignore_errors=True)
        return target
    return tmp


def _prune(root: Path, keep: Path) -> None:
    """Best effort: drop all but the newest unpacked trees, and stale temps."""
    try:
        entries = list(root.iterdir())
    except OSError:
        return
    now = time.time()
    done: list[tuple[float, Path]] = []
    for entry in entries:
        if entry == keep or not entry.is_dir():
            continue
        try:
            if entry.name.startswith(".tmp-"):
                if now - entry.stat().st_mtime > _STALE_TMP_SECONDS:
                    shutil.rmtree(entry, ignore_errors=True)
            elif (entry / _COMPLETE).is_file():
                done.append(((entry / _COMPLETE).stat().st_mtime, entry))
        except OSError:
            continue
    done.sort(reverse=True)
    for _, entry in done[_KEEP - 1 :]:
        shutil.rmtree(entry, ignore_errors=True)
