#!/usr/bin/env python3
"""Regenerate recipes/cuda-toolkit/redist.lock from NVIDIA's redist manifest.

NVIDIA publishes every CUDA release as per-component archives under
https://developer.download.nvidia.com/compute/cuda/redist/, described by a
``redistrib_<release>.json`` manifest that carries each archive's path and
sha256.  The cuda-toolkit recipe's build scripts download exactly the archives
listed in redist.lock and refuse any whose sha256 differs.  bash cannot parse
JSON without a tool cvcpkg does not ship, so the lock is a flat, line-oriented
extract of the manifest, and this script is the only thing that writes it.

Bumping the toolkit (see recipes/cuda-toolkit/recipe.yaml):

    python scripts/cuda_redist_lock.py 12.8.1

then set ``recipe.upstream_version`` to the same release and reset
``cvc_revision`` to 1.  The manifest is fetched over HTTPS from NVIDIA and its
own sha256 is recorded in the lock header, so a reviewer can re-derive every
line from it.

Usage:
    python scripts/cuda_redist_lock.py RELEASE [--manifest FILE] [--output FILE]
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
import urllib.request
from pathlib import Path

BASE_URL = "https://developer.download.nvidia.com/compute/cuda/redist"

# What the recipe installs: nvcc, the CUDA runtime, and the headers nvcc
# needs to compile anything (CCCL: thrust/cub/libcu++, which cuda_fp16.hpp
# already includes through <nv/target>).  This is the set libcvc's CI installs
# today (Jimver sub-packages nvcc, cudart, cudart-dev / visual_studio_integration)
# plus what those pull in.  Add a component (libcufft, cuda_nvrtc, ...) here
# and regenerate; the build scripts need no change for one that follows the
# usual bin/ include/ lib/ layout.
COMPONENTS: dict[str, tuple[str, ...]] = {
    "linux-x86_64": ("cuda_cccl", "cuda_cudart", "cuda_nvcc", "cuda_profiler_api"),
    "windows-x86_64": (
        "cuda_cccl",
        "cuda_cudart",
        "cuda_nvcc",
        "cuda_profiler_api",
        "visual_studio_integration",
    ),
}

DEFAULT_OUTPUT = Path(__file__).resolve().parents[1] / "recipes" / "cuda-toolkit" / "redist.lock"


def manifest_url(release: str) -> str:
    return f"{BASE_URL}/redistrib_{release}.json"


def render(release: str, manifest: bytes) -> str:
    """Return the lock text for *release* from the raw *manifest* bytes."""
    doc = json.loads(manifest)
    if doc.get("release_label") != release:
        raise SystemExit(f"manifest is for release {doc.get('release_label')!r}, not {release!r}")
    lines = [
        "# Generated by scripts/cuda_redist_lock.py -- do not edit by hand.",
        f"# Source manifest: {manifest_url(release)}",
        f"# Manifest sha256: {hashlib.sha256(manifest).hexdigest()}",
        "# Columns: <platform> <component> <version> <sha256> <archive path under",
        f"#   {BASE_URL}/> <component display name>",
        f"release {release}",
    ]
    for platform, components in COMPONENTS.items():
        for comp in components:
            entry = doc.get(comp)
            if not isinstance(entry, dict):
                raise SystemExit(f"{comp}: not in the {release} manifest")
            art = entry.get(platform)
            if not isinstance(art, dict):
                raise SystemExit(f"{comp}: no {platform} archive in the {release} manifest")
            name = " ".join(str(entry.get("name", comp)).split())
            lines.append(
                f"{platform} {comp} {entry['version']} {art['sha256']} "
                f"{art['relative_path']} {name}"
            )
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("release", help="CUDA release, e.g. 12.5.1")
    ap.add_argument(
        "--manifest",
        type=Path,
        help="read redistrib_<release>.json from this file instead of NVIDIA",
    )
    ap.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = ap.parse_args(argv)

    if args.manifest:
        raw = args.manifest.read_bytes()
    else:
        with urllib.request.urlopen(manifest_url(args.release)) as resp:  # noqa: S310
            raw = resp.read()
    args.output.write_text(render(args.release, raw), encoding="utf-8")
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
